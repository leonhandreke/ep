"""Catalogue tables: a simplified MusicBrainz model (see plans/backend.md).

Enumerations are stored as plain ``VARCHAR`` (``native_enum=False``) so that adding
a value does not need a migration of a Postgres enum type.

The schema is plain except for what the matcher and search (``ep.matching``) need:
``*_normalized`` columns, generated by the database as ``ep_normalize(<column>)`` (the
SQL twin of ``ep.matching.normalize.normalize``) with GIN trigram indexes, and indexes
for lookups by external ID, barcode, artist credit and recording (tracks). Foreign
keys that queries filter or join on are indexed (Postgres does not index them itself),
unless a unique constraint already starts with the column.
"""

import uuid
from enum import StrEnum
from typing import Any

import sqlalchemy as sa
from sqlalchemy import func
from sqlmodel import Field, Relationship

from ep.models.base import Base


def normalized(source: str, nullable: bool = False) -> Any:
    """A field for a stored generated column ``ep_normalize(source)``, for matching
    (null where ``source`` is null).

    Never set it: the database computes it on insert and update (SQLAlchemy fetches
    it back). Stored rather than an expression index, so that index rechecks and
    ranking read it instead of normalising every candidate again.
    """
    return Field(
        default=None,
        sa_column=sa.Column(
            sa.Text, sa.Computed(f"ep_normalize({source})", persisted=True), nullable=nullable
        ),
    )


def trigram_index(table: str, column: str) -> sa.Index:
    """A GIN trigram index on a normalised column, for the ``<%``/``%``/``LIKE`` operators."""
    return sa.Index(
        f"ix_{table}_{column}_trgm",
        column,
        postgresql_using="gin",
        postgresql_ops={column: "gin_trgm_ops"},
    )


def enum_column(enum: type[StrEnum]) -> sa.Enum:
    return sa.Enum(
        enum, native_enum=False, length=32, values_callable=lambda e: [m.value for m in e]
    )


class ArtistType(StrEnum):
    person = "person"
    group = "group"
    other = "other"


class ReleaseGroupType(StrEnum):
    album = "album"
    ep = "ep"
    single = "single"
    compilation = "compilation"
    other = "other"


class EntityType(StrEnum):
    """Entities that external IDs, notes and tags attach to, found by
    ``/search`` and ``/resolve``."""

    artist = "artist"
    release_group = "release_group"
    recording = "recording"
    radio_show = "radio_show"
    radio_episode = "radio_episode"


class Artist(Base, table=True):
    __table_args__ = (
        trigram_index("artist", "name_normalized"),
        trigram_index("artist", "sort_name_normalized"),
        trigram_index("artist", "original_name_normalized"),
        # The order of ``GET /artists``: the first pages read the index instead of
        # sorting every artist (and testing each for radio-only, ``ep.radio``).
        sa.Index("ix_artist_sort_name_name_id", "sort_name", "name", "id"),
    )

    mbid: uuid.UUID | None = Field(default=None, unique=True)
    name: str
    sort_name: str
    name_normalized: str = normalized("name")
    sort_name_normalized: str = normalized("sort_name")
    # The name in its own script when ``name`` is a Latin-script alias (MusicBrainz's
    # "跡部進一" for "Shinichi Atobe"); matched and searched like the name.
    original_name: str | None = None
    original_name_normalized: str | None = normalized("original_name", nullable=True)
    disambiguation: str = ""
    type: ArtistType | None = Field(default=None, sa_type=enum_column(ArtistType))


class ArtistCredit(Base, table=True):
    """An ordered list of credited artists, shared by every entity with the same credit.

    Credits are never edited in place: use ``ep.credits.get_or_create_artist_credit``.
    """

    __tablename__ = "artist_credit"

    __table_args__ = (
        trigram_index("artist_credit", "name_normalized"),
        # Finding a credit to reuse (named apart from the artist_credit_name table).
        sa.Index("ix_artist_credit_by_name", "name"),
    )

    # Rendered credit string, e.g. "Simon & Garfunkel".
    name: str
    name_normalized: str = normalized("name")

    names: list[ArtistCreditName] = Relationship(
        back_populates="artist_credit",
        cascade_delete=True,
        sa_relationship_kwargs={"order_by": "ArtistCreditName.position"},
    )


class ArtistCreditName(Base, table=True):
    __tablename__ = "artist_credit_name"
    __table_args__ = (sa.UniqueConstraint("artist_credit_id", "position"),)

    artist_credit_id: uuid.UUID = Field(foreign_key="artist_credit.id", ondelete="CASCADE")
    # Indexed: an artist's release groups and recordings, "is this artist credited".
    artist_id: uuid.UUID = Field(foreign_key="artist.id", index=True)
    position: int
    credited_name: str
    join_phrase: str = ""

    artist_credit: ArtistCredit = Relationship(back_populates="names")
    artist: Artist = Relationship()


class ReleaseGroup(Base, table=True):
    __tablename__ = "release_group"
    __table_args__ = (
        trigram_index("release_group", "title_normalized"),
        # Matching by barcode: a UPC-A is the EAN-13 with a leading zero.
        sa.Index("ix_release_group_barcode", func.ltrim(sa.column("barcode"), "0")),
    )

    mbid: uuid.UUID | None = Field(default=None, unique=True)
    # MBID of the one release we keep for this release group.
    release_mbid: uuid.UUID | None = Field(default=None, unique=True)
    title: str
    title_normalized: str = normalized("title")
    # Indexed for search ("artist title").
    artist_credit_id: uuid.UUID = Field(foreign_key="artist_credit.id", index=True)
    type: ReleaseGroupType = Field(sa_type=enum_column(ReleaseGroupType))
    # Partial date as text: YYYY, YYYY-MM or YYYY-MM-DD.
    date: str | None = None
    cover_path: str | None = None
    barcode: str | None = None

    artist_credit: ArtistCredit = Relationship()
    tracks: list[Track] = Relationship(
        back_populates="release_group",
        cascade_delete=True,
        sa_relationship_kwargs={"order_by": "[Track.disc, Track.position]"},
    )


class Recording(Base, table=True):
    __table_args__ = (trigram_index("recording", "title_normalized"),)

    mbid: uuid.UUID | None = Field(default=None, unique=True)
    title: str
    title_normalized: str = normalized("title")
    # Indexed for search ("artist title").
    artist_credit_id: uuid.UUID = Field(foreign_key="artist_credit.id", index=True)
    length_ms: int | None = None
    # The source the user chose to play (``ep.playability``); null: the best one. The
    # foreign key is added after the source table (``use_alter``: they refer to each
    # other); deleting the source clears it.
    preferred_source_id: uuid.UUID | None = Field(
        default=None,
        sa_column=sa.Column(
            sa.Uuid,
            sa.ForeignKey("source.id", ondelete="SET NULL", use_alter=True),
            nullable=True,
        ),
    )

    artist_credit: ArtistCredit = Relationship()
    tracks: list[Track] = Relationship(back_populates="recording")


class Track(Base, table=True):
    __table_args__ = (sa.UniqueConstraint("release_group_id", "disc", "position"),)

    release_group_id: uuid.UUID = Field(foreign_key="release_group.id", ondelete="CASCADE")
    # Indexed for search (a cover for each recording hit).
    recording_id: uuid.UUID = Field(foreign_key="recording.id", index=True)
    disc: int = 1
    position: int
    # Overrides the recording title on this release group when set.
    title: str | None = None

    release_group: ReleaseGroup = Relationship(back_populates="tracks")
    recording: Recording = Relationship(back_populates="tracks")


class ExternalId(Base, table=True):
    """An identifier in another system (ISRC, Bandcamp URL, Deezer ID, ...).

    ``entity_id`` points at the row of ``entity_type``; there is no foreign key, so
    deleting an entity must delete its external IDs (``ep.api.external_ids``).
    """

    __tablename__ = "external_id"
    __table_args__ = (
        sa.UniqueConstraint("entity_type", "entity_id", "scheme", "value"),
        # Matching by external ID.
        sa.Index("ix_external_id_scheme_value", "scheme", "value"),
    )

    entity_type: EntityType = Field(sa_type=enum_column(EntityType))
    entity_id: uuid.UUID
    scheme: str
    value: str
