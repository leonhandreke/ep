"""Trigram matching in Postgres: pg_trgm operators and thresholds.

Names and titles are compared through their ``*_normalized`` columns, generated by the
database with ``ep_normalize`` (the SQL twin of ``ep.matching.normalize.normalize``),
each with a GIN trigram index (``ep.models.catalogue``). Queries are normalised by
``ep_normalize`` too (``trigram_queries``), so both sides are normalised identically
even where the Python twin differs: Postgres treats combining marks without the Unicode
"Alphabetic" property (viramas, Thai and Myanmar signs) as separators, Python keeps
them. Python's ``normalize`` is for the rapidfuzz scores, which compare Python-normalised
text on both sides.

Indexes serve the pg_trgm *operators*, not the functions: ``query <% value`` (word
similarity of the query to the best-matching part of the value, at least
``pg_trgm.word_similarity_threshold``) and ``LIKE``. The threshold is a setting, so
``trigram_queries`` sets it for the current transaction (``set_config(..., true)``:
reset at commit or rollback, so it never leaks into another request on a pooled
connection). ``word_similarity`` and ``similarity`` (functions) then rank the rows found.
"""

import sqlalchemy as sa
from sqlalchemy import ColumnElement, func, literal
from sqlalchemy.orm import Mapped
from sqlmodel import Session


def word_similar(query: str, value: Mapped[str] | ColumnElement[str]) -> ColumnElement[bool]:
    """SQL ``query <% value``: the word similarity of the query (from ``trigram_queries``)
    to ``value`` is at least the threshold set there. Index-backed."""
    return literal(query).bool_op("<%")(value)


def trigram_queries(session: Session, threshold: float, *texts: str) -> list[str]:
    """Prepare trigram queries, in one statement: set ``pg_trgm.word_similarity_threshold``
    (0-1) until the end of the transaction, and return ``texts`` as ``ep_normalize`` gives
    them, i.e. normalised exactly like the stored ``*_normalized`` columns."""
    row = (
        session.connection()
        .execute(
            sa.select(
                func.set_config("pg_trgm.word_similarity_threshold", str(threshold), True),
                *(func.ep_normalize(text) for text in texts),
            )
        )
        .one()
    )
    return list(row[1:])
