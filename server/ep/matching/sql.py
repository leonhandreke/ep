"""Trigram matching in Postgres: pg_trgm operators and thresholds.

Names and titles are compared through their ``*_normalized`` columns, generated by the
database with ``ep_normalize``, the SQL twin of ``ep.matching.normalize.normalize``,
and each with a GIN trigram index (``ep.models.catalogue``). The query side is
normalised in Python with that function, so both sides are normalised identically.

Indexes serve the pg_trgm *operators*, not the functions: ``query <% value`` (word
similarity of the query to the best-matching part of the value, above
``pg_trgm.word_similarity_threshold``) and ``LIKE``. The threshold is a setting, so
``set_word_similarity_threshold`` sets it for the current transaction before each such
query. ``word_similarity`` and ``similarity`` (functions) then rank the rows found.
"""

from sqlalchemy import ColumnElement, func, literal
from sqlalchemy.orm import Mapped
from sqlmodel import Session, select


def word_similar(query: str, value: Mapped[str] | ColumnElement[str]) -> ColumnElement[bool]:
    """SQL ``query <% value``: the word similarity of the (normalised) query to ``value``
    is above the threshold set by ``set_word_similarity_threshold``. Index-backed."""
    return literal(query).bool_op("<%")(value)


def set_word_similarity_threshold(session: Session, threshold: float) -> None:
    """Set ``pg_trgm.word_similarity_threshold`` (0-1) until the end of the transaction."""
    session.exec(select(func.set_config("pg_trgm.word_similarity_threshold", str(threshold), True)))
